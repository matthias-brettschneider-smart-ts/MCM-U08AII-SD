// --- helpers -----------------------------------------------------------------

// --- tests -------------------------------------------------------------------

class ModuleNumber : public ::testing::Test
{
protected:

  void SetUp() override
  {
  }

  void TearDown() override
  {
  }
};

TEST_F(ModuleNumber, IsInvalidPerDefault)
{
  ASSERT_EQ(MODULE_NUMBER_GET(), MODULE_NUMBER_INVALID);
}

TEST_F(ModuleNumber, CanBeSet)
{
  MockStartupSetModuleNumber(13);
  ASSERT_EQ(MODULE_NUMBER_GET(), 13);
}

TEST_F(ModuleNumber, CanBeSetBetween0And255)
{
  for (uint16_t module_number = 0; module_number <= 255; module_number++) {
    MockStartupSetModuleNumber((uint8_t)module_number);
    ASSERT_EQ(MODULE_NUMBER_GET(), (uint8_t)module_number);
  }
}

