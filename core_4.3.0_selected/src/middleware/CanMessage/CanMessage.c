/*------------------------------------------------------------------------------
 *               F U N C T I O N   I N F O R M A T I O N
 *
 *
 *
 -----------------------------------------------------------------------------*/
uint8_t CanMessageGetLength(const bool can_fd, const uint8_t dlc)
{
  return (dlc <= 8) ? dlc : can_fd ? ((dlc == 9) ? 12 : (dlc == 10) ? 16 : (dlc == 11) ? 20 : (dlc == 12) ? 24 : (dlc == 13) ? 32 : (dlc == 14) ? 48 :
      (dlc == 15) ? 64 : CAN_MESSAGE_INVALID_LENGTH_OR_DLC) : 8;
}

/*------------------------------------------------------------------------------
 *               F U N C T I O N   I N F O R M A T I O N
 *
 *
 *
 -----------------------------------------------------------------------------*/
uint8_t CanMessageGetDlc(const bool can_fd, const uint8_t length)
{
  return (length <= 8) ? length : can_fd ? ((length > 64) ? CAN_MESSAGE_INVALID_LENGTH_OR_DLC : (length > 48) ? 15 : (length > 32) ? 14 : (length > 24) ? 13 :
      (length > 20) ? 12 : (length > 16) ? 11 : (length > 12) ? 10 : (length > 8) ? 9 : CAN_MESSAGE_INVALID_LENGTH_OR_DLC) : CAN_MESSAGE_INVALID_LENGTH_OR_DLC;
}

