// --- error -------------------------------------------------------------------

void ErrorAddEntry(e_ERROR_ID id, uint8_t attribute)
{
  (void)id;
  (void)attribute;

  mock.error_count++;
};

int MockErrorGetNumberAndReset(void)
{
  int temp = mock.error_count;
  mock.error_count = 0;

  return temp;
}

