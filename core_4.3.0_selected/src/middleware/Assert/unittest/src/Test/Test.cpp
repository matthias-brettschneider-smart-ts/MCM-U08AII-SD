// --- helpers -----------------------------------------------------------------

// --- tests -------------------------------------------------------------------

class Assert : public ::testing::Test {

  protected:

  void SetUp() override
  {
    ASSERT_EQ(MockErrorGetNumberAndReset(), 0);
  }

  void TearDown() override
  {
    ASSERT_EQ(MockErrorGetNumberAndReset(), 0);
  }
};

TEST_F(Assert, FatalAssertDoesNotLogErrorIfTrue)
{
  ASSERT_FATAL(true);
  ASSERT_EQ(MockErrorGetNumberAndReset(), 0);
}

TEST_F(Assert, FatalAssertLogsErrorIfFalse)
{
  ASSERT_FATAL(false);
  ASSERT_EQ(MockErrorGetNumberAndReset(), 1);
}

