/*------------------------------------------------------------------------------
 *               F U N C T I O N   I N F O R M A T I O N
 *
 * Get number of bytes from PRNG.
 *
 -----------------------------------------------------------------------------*/
size_t RandomPseudoGet(uint8_t output[], const size_t number_of_bytes)
{
  ASSERT_FATAL(output != NULL);
  ASSERT_FATAL(number_of_bytes == 4);

  // get four bytes that are not all zero
  uint32_t random = SYSTEM_TIMER_GET_TICKS_32() ^ 0x4711AFFEul;
  if (random == 0)
    random++;

  memcpy(output, &random, 4);

  return 4;
}

