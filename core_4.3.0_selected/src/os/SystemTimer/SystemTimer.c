/*------------------------------------------------------------------------------
 *               F U N C T I O N   I N F O R M A T I O N
 *
 * Create 32 bit free running timer.
 *
 *    size  |        overrun
 *   -------+----------------------
 *   16 Bit | ~  1,3 ms ..   1,6 ms
 *   32 Bit | ~ 85,9 s  .. 107,3 s
 *
 -----------------------------------------------------------------------------*/
void SystemTimerInit(void)
{
  ASSERT_FATAL(SYSTEM_TIMER_GET_FREQUENCY_IN_HZ() >= 40000000);
  ASSERT_FATAL(SYSTEM_TIMER_GET_FREQUENCY_IN_HZ() <= 50000000);
  TIMER_SET_FREQUENCY(SYSTEM_TIMER, SYSTEM_TIMER_GET_FREQUENCY_IN_HZ());
  TIMER_USE_AS_32_BIT(SYSTEM_TIMER);
  TIMER_SET_VALUE_16(SYSTEM_TIMER, 0);
  TIMER_SET_VALUE_16_UPPER(SYSTEM_TIMER, 0);
  TIMER_SET_PERIOD_16(SYSTEM_TIMER, UINT16_MAX);
  TIMER_SET_PERIOD_16_UPPER(SYSTEM_TIMER, UINT16_MAX);
  TIMER_START(SYSTEM_TIMER);
}

