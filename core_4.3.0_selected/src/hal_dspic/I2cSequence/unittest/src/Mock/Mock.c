// --- i2c ---------------------------------------------------------------------

void MockResetTransmission(void)
{
  memset(mock.transmission, 0, sizeof(mock.transmission));
  mock.index = 0;
}

bool MockTransmissionIsEqual(const char expected[], const size_t number_of_characters)
{
  bool equal = number_of_characters == mock.index;
  if (equal)
    equal = memcmp(expected, mock.transmission, number_of_characters) == 0;

  if (!equal) {
    printf("EXPECTED: %3d - %s\n", (int)number_of_characters, expected);
    printf("GOT:      %3d - %s\n", (int)mock.index, mock.transmission);
  }

  return equal;
}

