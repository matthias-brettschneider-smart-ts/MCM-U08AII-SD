  uint32_t SID    : 11;
  uint32_t EID    : 18;
  uint32_t SID11  :  1;
  uint32_t unused :  2;
  uint32_t DLC    :  4;
  uint32_t IDE    :  1;
  uint32_t RTR    :  1;
  uint32_t BRS    :  1;
